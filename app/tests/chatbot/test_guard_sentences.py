# 1층이 일부러 2층에 넘긴 문장 (10/16 수인 결정: 뜻이 갈리는 마음 표현은 2층이 판단)
LEFT_TO_LAYER2 = {"몇 년째 혼자라 사는 게 의미가 없어요"}


def _blocked(text: str) -> bool:
    rule = safety_rules.check(text)
    return rule.hit and context_check.looks_normal(text, rule) is None


def test_sentence_counts():
    assert len(SENTENCES) == 100
    assert sum(1 for _, label, _ in SENTENCES if label != "none") == 50


def test_layer1_misses_only_layer2_sentences():
    missed = {text for text, label, _ in SENTENCES if label != "none" and not _blocked(text)}
    assert missed == LEFT_TO_LAYER2


def test_layer1_blocks_no_normal_sentence():
    blocked = [text for text, label, _ in SENTENCES if label == "none" and _blocked(text)]
    assert blocked == []
