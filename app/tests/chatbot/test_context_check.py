@pytest.mark.parametrize("text", SHOULD_RELEASE)
def test_release(text):
    rule = check(text)
    assert rule.hit, "1층에 걸리는 문장이어야 시험이 의미 있음"
    assert looks_normal(text, rule) is not None


@pytest.mark.parametrize("text", SHOULD_KEEP)
def test_keep(text):
    rule = check(text)
    assert rule.hit
    assert looks_normal(text, rule) is None


@pytest.mark.parametrize("text", NO_LONGER_HIT)
def test_no_longer_hit(text):
    assert not check(text).hit
