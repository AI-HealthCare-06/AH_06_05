def emergency_patterns() -> list[tuple[str, str]]:
    gap = {"allergy": r"\S{0,2}?", "chest": r"\S{0,12}?"}  # 가슴은 "가슴이 아팠는데 지금 또 조여요"처럼 사이가 김
    out = [(name, a + gap.get(name, GAP) + b) for name, a, b in EMERGENCY_PAIRS]
    out.append(("poison", POISON + GAP + SWALLOW_PAST))
    # 갑자기, 아예 힘이 빠짐 / 넘어질 것 같음 / 주저앉음
    out.append(
        (
            "stroke",
            r"(갑자기|아예|하나도|전혀|쭉)\S{0,4}힘이\S{0,4}(없|안들어|빠지|빠져)|힘이(하나도|아예|전혀)\S{0,2}(없|안들어)",
        )
    )
    out.append(
        (
            "consciousness",
            r"(넘어질것같|주저앉|털썩|비틀거려서|휘청거려서)\S{0,10}(어지|힘이|못걷|아파|큰일)|(어지러워서|힘이없어서)\S{0,6}(넘어질|주저앉|못걷)|주저앉았",
        )
    )
    # 저혈당이 지금 의심됨, 심장이 미친 듯이 뜀, 피가 계속 남
    out.append(("hypoglycemia", r"저혈당(인가|인것|인듯|같)|저혈당\S{0,12}(지금|힘들|어지|떨|땀)"))
    out.append(("palpitation", r"(심장|가슴)(이)?\S{0,4}(미친듯|너무빨리|터질듯|막뛰|엄청빨리|쿵쾅쿵쾅|벌렁벌렁)"))
    out.append(
        ("bleeding", r"피(가)?\S{0,2}(계속|자꾸|막|줄줄)\S{0,2}(나|흘러|흐르)|입안(에)?피|피(를)?토할")
    )  # 검은 변은 safety_rules 조합 규칙에서
    # 뻣뻣해지거나 굳거나 떨리면서 움직이지 않음 (경련, 의식 저하)
    out.append(("consciousness", r"(뻣뻣|굳|떨리|떨려|떨면서|경련)\S{0,8}(안움직|움직이지않|움직이질않|못움직|미동)"))
    # 갑자기 굳음, 떨리더니 굳음, 대답이 없음, 쳐다보지 않음, 한쪽이 무거움, 말하기 힘듦, 얼굴이 하얘짐
    out.append(
        (
            "consciousness",
            r"(갑자기|자꾸|계속)\S{0,6}굳(어|었|는)|굳(어|었)\S{0,8}(떨|못움직|쳐다|일어날수)|(떨려서|떨리더니|떨리고)\S{0,8}(굳|일어날수없|못일어)",
        )
    )
    out.append(
        (
            "consciousness",
            r"(물어도|물어봐도|말해도|말걸어도)\S{0,4}대답|대답(이|도)?없(네|어|다|음|고)|쳐다보(질|지)않",
        )
    )
    out.append(
        (
            "stroke",
            SIDE
            + r"(이|가)?\S{0,2}(무거|마비|힘이|안움직|움직이질못|못움직|감각)|말(을)?하(기|는것)(가|도)?\S{0,2}(힘들|어렵)",
        )
    )
    out.append(("consciousness", r"(얼굴|낯|낯짝)(이)?\S{0,4}(하얘|창백|파래|퍼래|새파래)"))
    out.append(("bleeding", r"피토(했|까지|를)|(토할|토하|구토)\S{0,10}피(도|가)?\S{0,2}(나|나와)"))
    out.append(("palpitation", r"(심장|가슴)(이)?\S{0,8}듯\S{0,2}뛰"))
